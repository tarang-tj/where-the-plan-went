"""One set of silver/gold SQL, two engines.

  python -m wtpw.pipeline local    run bronze -> silver -> gold on DuckDB, export gold to data/work/gold_local/
  python -m wtpw.pipeline render   write pipeline/*.sql (Lakeflow materialized views) for the bundle

Only bronze differs by engine: DuckDB reads local files; Databricks reads the same files from the
Unity Catalog volume (Free Edition serverless cannot reach sec.gov, so files are uploaded).
CSV inputs are read as all-text on both engines; silver does every cast, so types match.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import duckdb

SQL = Path("sql")
WORK = Path("data/work")
PIPELINE = Path("pipeline")
VOLUME = "/Volumes/workspace/wtpw/raw"

# name -> (local path, volume file, format)
BRONZE = {
    "bronze_facts": ("data/work/facts.parquet", "facts.parquet", "parquet"),
    "bronze_guidance": ("curated/guidance_*.csv", "curated/guidance_*.csv", "csv"),
    "bronze_charges": ("curated/charges_*.csv", "curated/charges_*.csv", "csv"),
    "bronze_eac": ("curated/eac_*.csv", "curated/eac_*.csv", "csv"),
}
GOLD_EXPORT = ["gold_cube", "gold_bridge", "gold_guidance_error"]


def transforms() -> list[tuple[str, str]]:
    """(name, body) for every silver then gold file, in file order."""
    out = []
    for layer in ("silver", "gold"):
        for path in sorted((SQL / layer).glob("*.sql")):
            text = path.read_text()
            for chunk in re.split(r"(?m)^-- name: ", text)[1:]:
                name, _, body = chunk.partition("\n")
                out.append((name.strip(), body.strip().rstrip(";")))
    if not out:
        raise RuntimeError("no SQL transforms found under sql/")
    return out


def run_local(db_path: Path = WORK / "local.duckdb") -> duckdb.DuckDBPyConnection:
    con = duckdb.connect(str(db_path))
    for name, (local, _, fmt) in BRONZE.items():
        reader = (f"read_parquet('{local}')" if fmt == "parquet"
                  else f"read_csv('{local}', header=true, all_varchar=true)")
        con.execute(f"CREATE OR REPLACE TABLE {name} AS SELECT * FROM {reader}")
    for name, body in transforms():
        con.execute(f"CREATE OR REPLACE TABLE {name} AS {body}")
    out = WORK / "gold_local"
    out.mkdir(parents=True, exist_ok=True)
    for name in GOLD_EXPORT:
        con.execute(f"COPY (SELECT * FROM {name}) TO '{out / name}.csv' (HEADER)")
        print(f"{name}: {con.execute(f'SELECT count(*) FROM {name}').fetchone()[0]} rows")
    return con


def render() -> None:
    PIPELINE.mkdir(exist_ok=True)
    lines = ["-- GENERATED by `python -m wtpw.pipeline render` from sql/. Do not edit by hand.\n"]
    for name, (_, vol, fmt) in BRONZE.items():
        opts = "format => 'parquet'" if fmt == "parquet" else (
            "format => 'csv', header => true, inferSchema => false")
        lines.append(f"CREATE OR REFRESH MATERIALIZED VIEW {name} AS\n"
                     f"SELECT * FROM read_files('{VOLUME}/{vol}', {opts});\n")
    (PIPELINE / "bronze.sql").write_text("\n".join(lines))
    body = [lines[0]] + [f"CREATE OR REFRESH MATERIALIZED VIEW {n} AS\n{b};\n" for n, b in transforms()]
    (PIPELINE / "silver_gold.sql").write_text("\n".join(body))
    print(f"rendered {PIPELINE}/bronze.sql and {PIPELINE}/silver_gold.sql")


if __name__ == "__main__":
    {"local": run_local, "render": render}[sys.argv[1]]()
